use std::{env, fs, path::PathBuf};

fn main() {
    // Resolve the config directory. Treat an empty value as unset so a failed
    // CMake lookup falls back to the source tree rather than producing "/...".
    let config_dir = env::var("WASM_SEQ_CONFIG_DIR")
        .ok()
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| {
            let manifest = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR not set");
            // crate: fprime/Svc/WasmSequencer/fprime_spacewasm -> fprime/default/config
            PathBuf::from(manifest)
                .join("../../../default/config")
                .to_string_lossy()
                .into_owned()
        });

    let header = PathBuf::from(&config_dir).join("WasmSequencerSpacewasmConfig.h");

    // Rebuild when the pointer or the header contents change.
    println!("cargo:rerun-if-env-changed=WASM_SEQ_CONFIG_DIR");
    println!("cargo:rerun-if-changed={}", header.display());

    let text = fs::read_to_string(&header)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", header.display()));

    // Map the shared `#define WASM_SEQ_* <int>` macros onto the crate-local
    // const names used by lib.rs. Any other macro is ignored.
    let mut generated =
        String::from("// @generated by build.rs from WasmSequencerSpacewasmConfig.h\n");
    for line in text.lines() {
        let rest = match line.trim().strip_prefix("#define") {
            Some(r) => r,
            None => continue,
        };
        let mut fields = rest.split_whitespace();
        let (Some(name), Some(value)) = (fields.next(), fields.next()) else {
            continue;
        };
        let const_name = match name {
            "WASM_SEQ_SPACEWASM_PAGE_SIZE" => "PAGE_SIZE",
            "WASM_SEQ_SPACEWASM_MAX_PAGES" => "MAX_PAGES",
            "WASM_SEQ_MAX_SEQUENCERS" => "MAX_SEQUENCERS",
            _ => continue,
        };
        let parsed: usize = value.parse().unwrap_or_else(|_| {
            panic!("{name} must be a bare decimal integer literal, got {value:?}")
        });
        generated.push_str(&format!("pub const {const_name}: usize = {parsed};\n"));
    }

    // Fail loudly if the header stopped defining something lib.rs needs.
    for required in ["PAGE_SIZE", "MAX_PAGES", "MAX_SEQUENCERS"] {
        assert!(
            generated.contains(&format!("pub const {required}:")),
            "{} did not define {required}",
            header.display()
        );
    }

    let out_path =
        PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR not set")).join("wasm_seq_config.rs");
    fs::write(&out_path, generated).expect("failed to write generated config");
}
